export type IconName = keyof typeof PATHS;

export interface IconOptions {
  /** 提供后图标成为独立可访问对象；否则视为装饰性图标。 */
  label?: string;
  size?: number;
  className?: string;
}

export function icon(name: IconName, options: IconOptions = {}): Raw {
  const size = options.size ?? 16;
  const classes = ["icon", `icon-${name}`, options.className].filter(Boolean).join(" ");
  const accessibility = options.label ? `role="img" aria-label="${escapeHtml(options.label)}"` : 'aria-hidden="true"';
  return new Raw(
    `<svg xmlns="http://www.w3.org/2000/svg" class="${classes}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${accessibility} focusable="false">${PATHS[name]}</svg>`,
  );
}
